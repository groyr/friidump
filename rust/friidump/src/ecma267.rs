/// EDC を計算する。`edc` の初期値は通常 0。
///
/// C 版 `edc_calc(u32 edc, u8 *ptr, u32 len)` と等価。
pub fn edc_calc(mut edc: u32, data: &[u8]) -> u32 {
    for &b in data {
        let idx = (((edc >> 24) ^ (b as u32)) & 0xFF) as usize;
        edc = EDC_TABLE[idx] ^ (edc << 8);
    }
    edc
}

/// ECMA-267 の初期値（IV）。
pub const ECMA267_IVS: [u16; 16] = [
    0x0001, 0x5500, 0x0002, 0x2A00, 0x0004, 0x5400, 0x0008, 0x2800, 0x0010, 0x5000, 0x0020, 0x2001,
    0x0040, 0x4002, 0x0080, 0x0005,
];

/// 15 ビット LFSR。C 版のグローバル `LFSR` をカプセル化したもの。
#[derive(Clone, Copy, Debug)]
pub struct Lfsr {
    state: u16,
}

impl Lfsr {
    /// seed で LFSR を初期化する（C 版 `LFSR_init`）。
    pub fn new(seed: u16) -> Self {
        Self { state: seed }
    }

    /// ECMA-267 の IV インデックスで初期化する（C 版 `LFSR_ecma_init`）。
    pub fn from_iv(iv: usize) -> Self {
        Self::new(ECMA267_IVS[iv])
    }

    /// 1 ビット進めて出力ビットを返す（C 版 `LFSR_tick`）。
    pub fn tick(&mut self) -> u8 {
        let ret = self.state >> 14;
        let n = ret ^ ((self.state >> 10) & 1);
        self.state = ((self.state << 1) | n) & 0x7FFF;
        ret as u8
    }

    /// 8 ビット分進めて 1 バイト返す（C 版 `LFSR_byte`）。
    pub fn next_byte(&mut self) -> u8 {
        let mut ret: u8 = 0;
        for _ in 0..8 {
            ret = (ret << 1) | self.tick();
        }
        ret
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn edc_zero_input_is_zero() {
        assert_eq!(edc_calc(0, &[]), 0);
        assert_eq!(edc_calc(0, &[0u8; 16]), 0);
    }

    #[test]
    fn lfsr_is_deterministic_and_15bit() {
        // 同一 seed なら同一系列
        let mut a = Lfsr::new(0x1234);
        let mut b = Lfsr::new(0x1234);
        for _ in 0..1000 {
            assert_eq!(a.next_byte(), b.next_byte());
        }
        // 状態は常に 15 ビットに収まる
        let mut c = Lfsr::new(0x7FFF);
        for _ in 0..1000 {
            c.tick();
            assert!(c.state <= 0x7FFF);
        }
    }
}
